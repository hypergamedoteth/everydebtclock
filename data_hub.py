#!/usr/bin/env python3
"""Free data hub: /data/ page, CSV downloads, and chart images.

Generated by build.py from figures the site already publishes. Nothing here
estimates a missing year or mixes in the live clock projection. Each CSV row
carries a source and an as-of date. Charts are redrawn on every build.

Outputs (all under data/, which GitHub Pages serves at /data/):
  data/index.html
  data/us-debt-by-year.csv
  data/us-debt-by-president.csv
  data/us-debt-per-person.csv
  data/us-interest.csv
  data/us-state-debt.csv
  data/country-debt.csv
  data/charts/*.png and *.svg
"""
import csv, html, json, os
from PIL import Image, ImageDraw, ImageFont

import topics_build

DTP_URL = "https://fiscaldata.treasury.gov/datasets/debt-to-the-penny/debt-to-the-penny"
HDO_URL = "https://fiscaldata.treasury.gov/datasets/historical-debt-outstanding/historical-debt-outstanding"
OMB_URL = "https://www.govinfo.gov/app/collection/budget/2027/BUDGET-2027-TAB"
OMB_NAME = "OMB Historical Tables (FY2027 Budget)"
HDO_NAME = "Treasury, Historical Debt Outstanding"
DTP_NAME = "Treasury, Debt to the Penny"
CENSUS_STATE = "US Census Bureau, Annual Survey of State and Local Government Finances"
CENSUS_SURVEY = "https://www.census.gov/data/datasets/2024/econ/local/public-use-datasets.html"
POP_SHORT = {
    "historical-1900-1999": "1900–1999 estimates",
    "intercensal-2000-2010": "2000–2010 intercensal",
    "vintage-2020": "Vintage 2020",
    "vintage-2025": "Vintage 2025",
}
FD = "/usr/share/fonts/truetype/dejavu/"
def _font(name, size):
    return ImageFont.truetype(FD + name, size)

def _esc(s):
    return html.escape("" if s is None else str(s), quote=True)

def _num(x, nd=2):
    """Plain decimal. Blank when the source has no figure. No thousands separators.
    Dollar amounts (nd=2) always keep cents, so 110120.60 is not written as 110120.6."""
    if x is None or x == "":
        return ""
    q = round(float(x), nd)
    if nd == 2:
        return f"{q:.2f}"
    if abs(q - round(q)) < 10 ** (-nd):
        return str(int(round(q)))
    return f"{q:.{nd}f}".rstrip("0").rstrip(".")

def _write_csv(path, fields, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore", lineterminator="\n")
        w.writeheader()
        for row in rows:
            w.writerow({k: row.get(k, "") for k in fields})
    return len(rows)

def _official_close(T, M):
    td = T.get("debt_total") or {}
    closes = sorted((M.get("debt_closes") or []), key=lambda c: c[0], reverse=True)
    if td.get("status") == "ok" and closes and closes[0][0] == td.get("as_of"):
        return closes[0][0], float(closes[0][1])
    if td.get("status") == "ok":
        return td.get("as_of"), float(td.get("base"))
    return None, None

def _terms():
    import importlib.util
    spec = importlib.util.spec_from_file_location("debtclock_series", os.path.join(os.path.dirname(os.path.abspath(__file__)), "pipeline", "series.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.TERMS

def _load_omb(R):
    path = os.path.join(R, "cache", "omb_hist.json")
    try:
        data = json.load(open(path))["data"]
    except Exception:
        return {}, {}
    return data.get("t71") or {}, data.get("t12") or {}

def _src_join(names):
    out = []
    for n in names:
        if n and n not in out:
            out.append(n)
    return "; ".join(out)

def _family(source, tier):
    s = source or ""
    if "Eurostat" in s:
        return "Eurostat"
    if "QPSD" in s or "Quarterly Public Sector Debt" in s:
        return "QPSD"
    if tier == "imf" or s.startswith("IMF"):
        return "IMF"
    return "national"

