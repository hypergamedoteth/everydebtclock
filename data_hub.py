def build_debt_by_year(R, M):
    t71, t12 = _load_omb(R)
    by = {int(r[0]): (r[1], float(r[2])) for r in (M.get("debt_by_fy") or [])}
    years = sorted(set(by) | {int(y) for y in t71})
    hdo = M.get("debt_by_fy_source") or HDO_URL
    rows = []
    for y in years:
        a = by.get(y)
        r71 = t71.get(str(y))
        r12 = t12.get(str(y))
        gross = r71[6] if r71 and len(r71) > 6 else None
        public = r71[8] if r71 and len(r71) > 8 else None
        surplus = r12[4] if r12 and len(r12) > 4 else None
        sources = []
        if a:
            sources.append(HDO_NAME)
        if gross is not None or public is not None or surplus is not None:
            sources.append(OMB_NAME)
        rows.append({
            "fiscal_year": y,
            "total_debt_usd": _num(a[1]) if a else "",
            "omb_gross_debt_pct_gdp": _num(gross, 4) if gross is not None else "",
            "omb_held_by_public_pct_gdp": _num(public, 4) if public is not None else "",
            "omb_surplus_pct_gdp": _num(surplus, 4) if surplus is not None else "",
            "source": _src_join(sources),
            "source_url": hdo if a else OMB_URL,
            "as_of": a[0] if a else "",
        })
    fields = ["fiscal_year", "total_debt_usd", "omb_gross_debt_pct_gdp", "omb_held_by_public_pct_gdp",
              "omb_surplus_pct_gdp", "source", "source_url", "as_of"]
    return fields, rows

def build_presidents(R, M, off_d, off_v):
    H = topics_build._load(R)
    hdo = M.get("debt_by_fy") or []
    rows = []
    for name, n, start, end in _terms():
        a = topics_build._point(start, H, hdo)
        open_term = end is None
        if open_term:
            b = {"date": off_d, "amount": off_v, "basis": "dtp", "requested": off_d} if off_d and off_v is not None else None
        else:
            b = topics_build._point(end, H, hdo)
        same = a and b and a["date"] == b["date"]
        change = pct = None
        if a and b and not same and a.get("amount"):
            change = b["amount"] - a["amount"]
            pct = change / a["amount"] * 100
        bases = []
        if a:
            bases.append(a["basis"])
        if b:
            bases.append(b["basis"])
        srcs = []
        if "dtp" in bases:
            srcs.append(DTP_NAME)
        if "hdo" in bases:
            srcs.append(HDO_NAME)
        rows.append({
            "president": name,
            "term_number": n,
            "term_start": start,
            "term_end": "" if open_term else end,
            "term_in_progress": "yes" if open_term else "no",
            "debt_start_usd": _num(a["amount"]) if a else "",
            "debt_start_date": a["date"] if a else "",
            "debt_start_basis": ({"dtp": "Debt to the Penny, last close on or before the date",
                                  "hdo": "Historical Debt Outstanding, annual record (not inauguration day)"}.get(a["basis"], a["basis"]) if a else ""),
            "debt_end_usd": _num(b["amount"]) if b else "",
            "debt_end_date": b["date"] if b else "",
            "debt_end_basis": ("latest close, term in progress" if open_term and b else
                               {"dtp": "Debt to the Penny, last close on or before the date",
                                "hdo": "Historical Debt Outstanding, annual record (not inauguration day)"}.get(b["basis"], "") if b else ""),
            "change_usd": _num(change) if change is not None else "",
            "change_pct": _num(pct, 4) if pct is not None else "",
            "source": _src_join(srcs),
            "source_url": DTP_URL if "dtp" in bases else HDO_URL,
            "as_of": (b["date"] if b else (a["date"] if a else "")),
        })
    fields = ["president", "term_number", "term_start", "term_end", "term_in_progress",
              "debt_start_usd", "debt_start_date", "debt_start_basis",
              "debt_end_usd", "debt_end_date", "debt_end_basis",
              "change_usd", "change_pct", "source", "source_url", "as_of"]
    return fields, rows, H

def build_per_person(M, H, T, off_d, off_v):
    by = {int(r[0]): (r[1], float(r[2])) for r in (M.get("debt_by_fy") or [])}
    pops = {p["year"]: p for p in H["population_by_year"]}
    pop = T.get("population") or {}
    hh = T.get("households") or {}
    tax = T.get("tax_returns") or {}
    rows = []
    if off_v is not None and pop.get("base") and hh.get("base") and tax.get("base"):
        rows.append({
            "row_type": "official_close",
            "fiscal_year": "",
            "total_debt_usd": _num(off_v),
            "population": int(pop["base"]),
            "population_as_of": pop.get("as_of") or "",
            "population_series": "Vintage 2025",
            "debt_per_person_usd": _num(off_v / pop["base"]),
            "households": int(hh["base"]),
            "households_as_of": hh.get("as_of") or "",
            "debt_per_household_usd": _num(off_v / hh["base"]),
            "tax_returns_filed": int(tax["base"]),
            "tax_returns_period": tax.get("as_of") or "",
            "debt_per_tax_return_usd": _num(off_v / tax["base"]),
            "source": _src_join([DTP_NAME, pop.get("source_name") or "Census Bureau, Vintage 2025",
                                 hh.get("source_name") or "", tax.get("source_name") or ""]),
            "source_url": DTP_URL,
            "as_of": off_d or "",
        })
    recent = [y for y in sorted(by) if y >= 2000]
    older = [y for y in sorted(set(by) & set(pops)) if y < 2000]
    hdo_src = M.get("debt_by_fy_source") or HDO_URL
    for y in older + recent:
        debt = by.get(y)
        if not debt:
            continue
        p = pops.get(y)
        per = series = pdate = pop_n = ""
        src = HDO_NAME
        if p:
            per = _num(debt[1] / p["population"])
            series = POP_SHORT.get(p["series"], p["series"])
            pdate = f"{y}-07-01"
            pop_n = int(p["population"])
            src = _src_join([HDO_NAME, p.get("source_name") or "Census Bureau"])
        rows.append({
            "row_type": "fiscal_year",
            "fiscal_year": y,
            "total_debt_usd": _num(debt[1]),
            "population": pop_n,
            "population_as_of": pdate,
            "population_series": series,
            "debt_per_person_usd": per,
            "households": "",
            "households_as_of": "",
            "debt_per_household_usd": "",
            "tax_returns_filed": "",
            "tax_returns_period": "",
            "debt_per_tax_return_usd": "",
            "source": src,
            "source_url": hdo_src,
            "as_of": debt[0],
        })
    fields = ["row_type", "fiscal_year", "total_debt_usd", "population", "population_as_of", "population_series",
              "debt_per_person_usd", "households", "households_as_of", "debt_per_household_usd",
              "tax_returns_filed", "tax_returns_period", "debt_per_tax_return_usd", "source", "source_url", "as_of"]
    return fields, rows

def build_interest(R, T):
    H = topics_build._load(R)
    cash = T.get("interest_cash") or {}
    expenses = {r["fy"]: r for r in H["interest_expense_by_fy"]}
    nets = {r["fy"]: r for r in H["net_interest_by_fy"]}
    latest = H.get("net_interest_latest") or {}
    rows = []
    if cash.get("status") == "ok" and cash.get("base") is not None:
        rows.append({
            "series": "dts_cash_interest",
            "fiscal_year": cash.get("fy") or "",
            "amount_usd": _num(cash["base"]),
            "complete": "no",
            "note": "Daily Treasury Statement cash interest paid on Treasury securities, fiscal year to date. Not the projected clock.",
            "source": cash.get("source_name") or "Treasury Daily Treasury Statement (Interest on Treasury Securities)",
            "source_url": cash.get("source") or H["sources"]["dts_interest_paid"],
            "as_of": cash.get("as_of") or "",
        })
    years = sorted(set(expenses) | set(nets) | ({latest["fy"]} if latest.get("fy") else set()))
    for y in years:
        n = nets.get(y)
        if n:
            rows.append({
                "series": "mts_net_interest",
                "fiscal_year": y,
                "amount_usd": _num(n["amount"]),
                "complete": "yes" if str(n["date"])[5:7] == "09" else "no",
                "note": "MTS Table 9, line 320, September year-to-date (full fiscal year)." if str(n["date"])[5:7] == "09" else "MTS Table 9, line 320.",
                "source": "Treasury, Monthly Treasury Statement (net interest, line 320)",
                "source_url": H["sources"]["mts_net_interest"],
                "as_of": n["date"],
            })
        elif latest.get("fy") == y and latest.get("amount") is not None:
            rows.append({
                "series": "mts_net_interest",
                "fiscal_year": y,
                "amount_usd": _num(latest["amount"]),
                "complete": "no",
                "note": "MTS Table 9, line 320, year to date, not a finished year.",
                "source": "Treasury, Monthly Treasury Statement (net interest, line 320)",
                "source_url": H["sources"]["mts_net_interest"],
                "as_of": latest.get("date") or "",
            })
        e = expenses.get(y)
        if e:
            rows.append({
                "series": "interest_expense",
                "fiscal_year": y,
                "amount_usd": _num(e["amount"]),
                "complete": "yes" if e.get("complete") else "no",
                "note": "Treasury Interest Expense on the Public Debt Outstanding, September year-to-date." if e.get("complete") else "Interest-expense dataset, year to date, not a full year.",
                "source": "Treasury, Interest Expense on the Public Debt Outstanding",
                "source_url": H["sources"]["interest_expense"],
                "as_of": e["date"],
            })
    fields = ["series", "fiscal_year", "amount_usd", "complete", "note", "source", "source_url", "as_of"]
    return fields, rows

def build_states(places):
    import places_build
    rows = []
    for p in sorted((x for x in places if x.get("kind") == "state"), key=lambda x: x["name"]):
        c = places_build.calc(p)
        pop = p["population"]
        parts = {comp["key"]: comp for comp in p["components"]}
        src_names = []
        src_url = ""
        for comp in p["components"]:
            if comp.get("source_name") and comp["source_name"] not in src_names:
                src_names.append(comp["source_name"])
            if not src_url and comp.get("source_url"):
                src_url = comp["source_url"]
        total = c["total"]
        rows.append({
            "state": p["name"],
            "slug": p["slug"],
            "region_code": p.get("region_code") or "",
            "total_debt_usd": _num(total),
            "state_government_debt_usd": _num(parts["state"]["value"]) if "state" in parts else "",
            "local_government_debt_usd": _num(parts["local"]["value"]) if "local" in parts else "",
            "population": int(pop["value"]),
            "population_as_of": pop.get("as_of") or "",
            "debt_per_person_usd": _num(total / pop["value"]) if pop.get("value") else "",
            "measure": p.get("headline_long") or p.get("headline") or "state and local government debt",
            "source": _src_join(src_names) or p.get("publisher") or CENSUS_STATE,
            "source_url": src_url,
            "as_of": c["as_of"],
        })
    fields = ["state", "slug", "region_code", "total_debt_usd", "state_government_debt_usd", "local_government_debt_usd",
              "population", "population_as_of", "debt_per_person_usd", "measure", "source", "source_url", "as_of"]
    return fields, rows

