def _nice_max(v):
    if v <= 0:
        return 1
    import math
    exp = math.floor(math.log10(v))
    base = v / 10 ** exp
    for step in (1, 1.2, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10):
        if base <= step:
            return step * 10 ** exp
    return 10 ** (exp + 1)

def _fmt_tick(v, unit):
    if abs(v - round(v)) < 1e-6:
        return f"{round(v):.0f}"
    return f"{v:.1f}"

def _render(path_stem, title, subtitle, labels, values, unit, kind):
    """Draw one chart as SVG and PNG. values are already in `unit` (trillion, billion, or pct)."""
    if not values or max(values) <= 0:
        return None
    W = 1200
    n = len(values)
    if kind == "bar":
        H = max(520, 118 + n * 26 + 56)
        plot_l, plot_r, plot_t, plot_b = 268, 1140, 86, H - 64
    else:
        H = 720
        plot_l, plot_r, plot_t, plot_b = 86, 1140, 96, 620
    ymax = _nice_max(max(values) * 1.06)
    credit = "EveryDebtClock.com"
    axis = {"trillion": "Trillion dollars", "billion": "Billion dollars", "pct": "Percent of GDP"}[unit]

    def y_of(v, top, bot):
        return bot - (v / ymax) * (bot - top)

    # SVG
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img">',
             f'<title>{_esc(title)}</title>',
             f'<rect width="{W}" height="{H}" fill="#07090d"/>',
             f'<rect x="0" y="0" width="{W}" height="6" fill="#ff4d5e"/>',
             f'<text x="36" y="42" fill="#e8edf5" font-family="DejaVu Sans, sans-serif" font-size="22" font-weight="700">{_esc(title)}</text>',
             f'<text x="36" y="66" fill="#8a97ab" font-family="DejaVu Sans, sans-serif" font-size="14">{_esc(subtitle)}</text>']
    ticks = 4
    for i in range(ticks + 1):
        val = ymax * i / ticks
        if kind == "bar":
            x = plot_l + (val / ymax) * (plot_r - plot_l)
            parts.append(f'<line x1="{x:.1f}" y1="{plot_t}" x2="{x:.1f}" y2="{plot_b}" stroke="#1c2533" stroke-width="1"/>')
            parts.append(f'<text x="{x:.1f}" y="{plot_b + 18}" fill="#8a97ab" font-family="DejaVu Sans, sans-serif" font-size="12" text-anchor="middle">{_fmt_tick(val, unit)}</text>')
        else:
            y = y_of(val, plot_t, plot_b)
            parts.append(f'<line x1="{plot_l}" y1="{y:.1f}" x2="{plot_r}" y2="{y:.1f}" stroke="#1c2533" stroke-width="1"/>')
            parts.append(f'<text x="{plot_l - 10}" y="{y + 4:.1f}" fill="#8a97ab" font-family="DejaVu Sans, sans-serif" font-size="12" text-anchor="end">{_fmt_tick(val, unit)}</text>')
    if kind == "line":
        pts = []
        for i, v in enumerate(values):
            x = plot_l if n == 1 else plot_l + i * (plot_r - plot_l) / (n - 1)
            y = y_of(v, plot_t, plot_b)
            pts.append((x, y))
        poly = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
        parts.append(f'<polyline fill="none" stroke="#ff4d5e" stroke-width="3" points="{poly}"/>')
        step = 1
        while n > 16 and (n / step) > 12:
            step += 1
        # Prefer decade labels when the labels are years.
        shown = set()
        for i, lab in enumerate(labels):
            show = (i == 0 or i == n - 1)
            if str(lab).isdigit() and int(lab) % 10 == 0:
                show = True
            elif not str(lab).isdigit() and i % step == 0:
                show = True
            if not show or i in shown:
                continue
            shown.add(i)
            x = pts[i][0]
            parts.append(f'<text x="{x:.1f}" y="{plot_b + 22}" fill="#8a97ab" font-family="DejaVu Sans, sans-serif" font-size="12" text-anchor="middle">{_esc(lab)}</text>')
        parts.append(f'<text x="{plot_l}" y="{H - 28}" fill="#5c687a" font-family="DejaVu Sans, sans-serif" font-size="13">{_esc(axis)}</text>')
    else:
        gap = (plot_b - plot_t) / n
        for i, (lab, v) in enumerate(zip(labels, values)):
            y = plot_t + i * gap
            h = gap * 0.62
            w = (v / ymax) * (plot_r - plot_l)
            parts.append(f'<text x="{plot_l - 12}" y="{y + h * 0.75:.1f}" fill="#c9d3e2" font-family="DejaVu Sans, sans-serif" font-size="13" text-anchor="end">{_esc(_clip(lab))}</text>')
            parts.append(f'<rect x="{plot_l}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="#5aa9ff" rx="2"/>')
        parts.append(f'<text x="{plot_l}" y="{H - 16}" fill="#5c687a" font-family="DejaVu Sans, sans-serif" font-size="13">{_esc(axis)}</text>')
    parts.append(f'<text x="{W - 28}" y="{H - 16}" fill="#5aa9ff" font-family="DejaVu Sans, sans-serif" font-size="16" font-weight="700" text-anchor="end">{credit}</text>')
    parts.append("</svg>")
    svg_path = path_stem + ".svg"
    open(svg_path, "w", encoding="utf-8").write("".join(parts))

    im = Image.new("RGB", (W, H), "#07090d")
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, W, 6], fill="#ff4d5e")
    d.text((36, 22), title, font=_font("DejaVuSans-Bold.ttf", 22), fill="#e8edf5")
    d.text((36, 50), subtitle, font=_font("DejaVuSans.ttf", 14), fill="#8a97ab")
    for i in range(ticks + 1):
        val = ymax * i / ticks
        label = _fmt_tick(val, unit)
        if kind == "bar":
            x = plot_l + (val / ymax) * (plot_r - plot_l)
            d.line([(x, plot_t), (x, plot_b)], fill="#1c2533")
            tw = d.textlength(label, font=_font("DejaVuSans.ttf", 12))
            d.text((x - tw / 2, plot_b + 6), label, font=_font("DejaVuSans.ttf", 12), fill="#8a97ab")
        else:
            y = y_of(val, plot_t, plot_b)
            d.line([(plot_l, y), (plot_r, y)], fill="#1c2533")
            tw = d.textlength(label, font=_font("DejaVuSans.ttf", 12))
            d.text((plot_l - 10 - tw, y - 8), label, font=_font("DejaVuSans.ttf", 12), fill="#8a97ab")
    if kind == "line":
        pts = []
        for i, v in enumerate(values):
            x = plot_l if n == 1 else plot_l + i * (plot_r - plot_l) / (n - 1)
            y = y_of(v, plot_t, plot_b)
            pts.append((x, y))
        d.line(pts, fill="#ff4d5e", width=3)
        shown = set()
        for i, lab in enumerate(labels):
            show = (i == 0 or i == n - 1)
            if str(lab).isdigit() and int(lab) % 10 == 0:
                show = True
            if not show or i in shown:
                continue
            shown.add(i)
            lab_s = str(lab)
            tw = d.textlength(lab_s, font=_font("DejaVuSans.ttf", 12))
            d.text((pts[i][0] - tw / 2, plot_b + 8), lab_s, font=_font("DejaVuSans.ttf", 12), fill="#8a97ab")
        d.text((plot_l, H - 44), axis, font=_font("DejaVuSans.ttf", 13), fill="#5c687a")
    else:
        gap = (plot_b - plot_t) / n
        for i, (lab, v) in enumerate(zip(labels, values)):
            y = plot_t + i * gap
            h = gap * 0.62
            w = (v / ymax) * (plot_r - plot_l)
            lab_s = _clip(lab)
            tw = d.textlength(lab_s, font=_font("DejaVuSans.ttf", 13))
            d.text((plot_l - 12 - tw, y + max(0, (h - 13) / 2)), lab_s, font=_font("DejaVuSans.ttf", 13), fill="#c9d3e2")
            d.rectangle([plot_l, y, plot_l + w, y + h], fill="#5aa9ff")
        d.text((plot_l, H - 32), axis, font=_font("DejaVuSans.ttf", 13), fill="#5c687a")
    cw = d.textlength(credit, font=_font("DejaVuSans-Bold.ttf", 16))
    d.text((W - 28 - cw, H - 32), credit, font=_font("DejaVuSans-Bold.ttf", 16), fill="#5aa9ff")
    png_path = path_stem + ".png"
    im.save(png_path, optimize=True)
    return svg_path, png_path

def _clip(s, n=34):
    s = str(s)
    return s if len(s) <= n else s[:n - 1] + "…"

def _pres_label(name, n):
    if name.startswith("George H. W."):
        last = "G.H.W. Bush"
    elif name.startswith("George W."):
        last = "G.W. Bush"
    else:
        last = name.split()[-1]
    return f"{last} {n}"

def draw_charts(R, year_rows, pres_rows, interest_rows, country_rows):
    dest = os.path.join(R, "data", "charts")
    os.makedirs(dest, exist_ok=True)
    made = {}
    years = [r for r in year_rows if r["total_debt_usd"] and int(r["fiscal_year"]) >= 1940]
    if years:
        _render(os.path.join(dest, "us-debt-by-year"),
                "US national debt by fiscal year",
                "Treasury Historical Debt Outstanding, FY1940 on. Earlier years are in the CSV.",
                [str(r["fiscal_year"]) for r in years],
                [float(r["total_debt_usd"]) / 1e12 for r in years],
                "trillion", "line")
        made["us-debt-by-year"] = {"title": "US national debt by fiscal year", "alt": "Line chart of US national debt by fiscal year from FY1940"}
    pres = [r for r in pres_rows if r["debt_end_usd"] and (r["term_in_progress"] == "yes" or (r["term_end"] and r["term_end"] >= "1945-01-20"))]
    pres = list(reversed(pres))
    if pres:
        _render(os.path.join(dest, "us-debt-by-president"),
                "US national debt at the end of each term",
                "Terms ending in 1945 or later. Debt to the Penny where it exists; annual records before that.",
                [_pres_label(r["president"], r["term_number"]) for r in pres],
                [float(r["debt_end_usd"]) / 1e12 for r in pres],
                "trillion", "bar")
        made["us-debt-by-president"] = {"title": "US national debt by president", "alt": "Bar chart of US national debt at the end of each presidential term since 1945"}
    interest = [r for r in interest_rows if r["series"] == "mts_net_interest" and r["complete"] == "yes" and r["amount_usd"]]
    if interest:
        _render(os.path.join(dest, "us-interest-by-year"),
                "US net interest by fiscal year",
                "Monthly Treasury Statement, Table 9, line 320. Complete fiscal years only.",
                [str(r["fiscal_year"]) for r in interest],
                [float(r["amount_usd"]) / 1e9 for r in interest],
                "billion", "line")
        made["us-interest-by-year"] = {"title": "US net interest by fiscal year", "alt": "Line chart of US net interest on the debt by fiscal year"}
    ranked = [r for r in country_rows if r["debt_to_gdp_pct"] != ""]
    ranked.sort(key=lambda r: (-float(r["debt_to_gdp_pct"]), r["country"]))
    top = ranked[:20]
    if top:
        _render(os.path.join(dest, "countries-debt-to-gdp"),
                "Top 20 countries by debt-to-GDP",
                "General government gross debt. IMF ratio, or the world-clock stock divided by IMF 2026 GDP.",
                [r["country"] for r in top],
                [float(r["debt_to_gdp_pct"]) for r in top],
                "pct", "bar")
        made["countries-debt-to-gdp"] = {"title": "Top 20 countries by debt-to-GDP", "alt": "Bar chart of the 20 countries with the highest general-government debt-to-GDP"}
    keep = set()
    for slug in made:
        keep.add(slug + ".svg")
        keep.add(slug + ".png")
    for name in os.listdir(dest):
        if name not in keep and (name.endswith(".png") or name.endswith(".svg")):
            os.remove(os.path.join(dest, name))
    return made

